export const COLOR_CODES: readonly string[] = PALETTE.colors.map((c) => c.code)
export const COLOR_SET: ReadonlySet<string> = new Set(COLOR_CODES)
export const GROUP_ORDER: readonly string[] = ["A", "B", "C", "D", "E", "F", "G", "H", "M"]

const GROUP_INDEX: Record<string, number> = Object.fromEntries(GROUP_ORDER.map((g, i) => [g, i]))

export function parseColorCode(code: string): { group: string; n: number } | null {
  const m = /^([A-HM])(\d+)$/.exec(code.trim().toUpperCase())
  if (!m) return null
  return { group: m[1], n: Number(m[2]) }
}

export function normalizeColorCode(input: string): string | null {
  const parsed = parseColorCode(input)
  if (!parsed) return null
  const code = parsed.group + String(parsed.n)
  return COLOR_SET.has(code) ? code : null
}

export function compareColorCode(a: string, b: string): number {
  const pa = parseColorCode(a)
  const pb = parseColorCode(b)
  if (!pa || !pb) return a.localeCompare(b)
  const gi = (GROUP_INDEX[pa.group] ?? 99) - (GROUP_INDEX[pb.group] ?? 99)
  if (gi !== 0) return gi
  return pa.n - pb.n
}

export function colorByCode(code: string): PaletteColor | undefined {
  return PALETTE.colors.find((c) => c.code === code)
}

